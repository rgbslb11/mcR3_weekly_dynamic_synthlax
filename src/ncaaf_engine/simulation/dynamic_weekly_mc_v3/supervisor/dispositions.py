"""The epistemic disposition of a production parameter, and what it permits.

R1 could represent one thing: a parameter was fitted, or the run refused. The R2
evidence proves the final V3 vector will not look like that. Some parameters
carry a fitted number, some carry a governed number nobody fitted, some carry a
number a human has to choose, and some carry no number at all because the
evidence cannot produce one. Those are different epistemic claims, and a
recommendation that flattened them into "value / no value" would tell an
approver less than the run actually knows.

So a disposition is a first-class value here, and every governed parameter
carries exactly one. Nine are recognised and the set is closed: an unrecognised
disposition is refused rather than treated as unknown-but-probably-fine, for the
same reason ``UNCLASSIFIED`` circularity is refused in :mod:`.evidence`.

Three properties do the work
-----------------------------

**Only one disposition may enter an estimator.** :data:`ESTIMATOR_ADMISSIBLE` is
``(FIT_RESULT,)`` and :func:`require_estimator_admissible` is what every
numerical stage calls. A circular parameter cannot reach a search by being
described differently, because the search asks about the disposition rather than
about the words in the rationale.

**Carrying a value and having been measured are different facts.**
:data:`CARRIES_VALUE` names the four dispositions under which a number is
legitimate -- a fit result, a fixed prior, a prior-only value, and a residual
derived from other accepted quantities. The rest must recommend ``None``, and
:func:`require_value_consistent` refuses the combination rather than trusting a
note beside it.

**Absence is classified, not silently tolerated.** A parameter with no value is
either a thing a human must choose or a fail-closed hole.
:data:`PRODUCTION_VALUE_SEMANTICS` says which, per parameter, and
:func:`execution_obstacles` turns that into the concrete list of reasons a run
may not enter its execution tiers. This is where the FCS doctrine lives: the FCS
point adapter is required *at its use site*, so a run whose adapter is
:data:`MISSING_FAIL_CLOSED` may execute, and every FCS game that needs a point
adapter fails closed instead of receiving an invented number.
"""

