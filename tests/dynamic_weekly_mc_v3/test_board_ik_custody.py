@pytest.mark.parametrize(
    "variant",
    [
        "2026_Board_I-K_CANONICAL_APPROVED_R1_REISSUE(3).xlsx",
        "2026_Board_I-K_CANONICAL_APPROVED_R1_REISSUE(3)(1).xlsx",
        "2026_Board_I-K_CANONICAL_APPROVED_R1_REISSUE(3)(1) (1).xlsx",
        "2026_Board_I-K_CANONICAL_APPROVED_R1_REISSUE (1).xlsx",
    ],
)
def test_the_approved_bytes_verify_under_download_name_variants(variant, tmp_path):
    """The ruling names one artifact; delivery channels rename it freely."""
    copy = tmp_path / variant
    shutil.copy(APPROVED, copy)
    assert bor.board_of_record_status(copy)["custody"] == bor.CUSTODY_VERIFIED
    assert bor.require_board_of_record(copy).row_count == 121
    assert bor.board_of_record_blockers(copy) == []


def test_the_approved_bytes_verify_even_under_a_foreign_name(tmp_path):
    """Content identity is authoritative, so a misleading name cannot veto it.

    The converse — a correct name over wrong bytes — is refused immediately
    below, which is where the asymmetry actually protects the board.
    """
    copy = tmp_path / "Board_I-H_historical_evidence.xlsx"
    shutil.copy(APPROVED, copy)
    assert bor.board_of_record_status(copy)["custody"] == bor.CUSTODY_VERIFIED


def test_the_canonical_filename_over_wrong_bytes_is_refused(tmp_path):
    """Correct name / wrong digest — the filename-only match, refused."""
    impostor = _synthetic_board(
        tmp_path / bor.BOARD_OF_RECORD_FILENAME, _plausible_rows()
    )
    assert impostor.name == bor.BOARD_OF_RECORD_FILENAME
    status = bor.board_of_record_status(impostor)
    assert status["custody"] == bor.CUSTODY_BINARY_MISMATCH
    assert status["verified"] is False
    assert status["blocker"] == bor.BOARD_OF_RECORD_BLOCKER
    with pytest.raises(GovernanceBlock, match="filename is not authority"):
        bor.require_board_of_record(impostor)


