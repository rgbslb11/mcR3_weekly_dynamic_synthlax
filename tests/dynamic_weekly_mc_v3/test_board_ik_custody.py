def _synthetic_board(path: Path, rows: list[list[object]], sheet: str | None = None) -> Path:
    """A workbook shaped like the Board but built here — never the real artifact."""
    wb = Workbook()
    ws = wb.active
    ws.title = sheet or bor.BOARD_SHEET
    ws.append(["2026 BOARD I-K — SYNTHETIC TEST FIXTURE"])
    ws.append(["Generated by the test suite. Not a governed artifact."])
    ws.append(list(bor.BOARD_COLUMNS))
    for row in rows:
        ws.append(row)
    wb.save(path)
    return path


def _plausible_rows(count: int = 121) -> list[list[object]]:
    return [
        [i, f"Team {i}", f"T{i}", "Test", 0.5, 0.5, 0.5, 0.5, 0.5, 0.5, 0.5,
         None, 0.5, "BLOCKED_INPUTS_UNAVAILABLE", i, 0, str(i)]
        for i in range(1, count + 1)
    ]


def _grid(rows: list[list[object]]) -> list[list[object]]:
    """Header row plus data rows, the shape ``_read_board_grid`` returns."""
    return [list(bor.BOARD_COLUMNS)] + [list(r) for r in rows]


