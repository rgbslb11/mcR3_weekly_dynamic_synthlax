"""Board I-K artifact custody — content identity, schema, governed identities.

The rule this suite exists to enforce is that **content decides custody and a
filename never does**. Both directions are tested explicitly:

* the approved bytes verify under any name, including the browser
  de-duplication variants ``(3)``, ``(3)(1)`` and `` (1)`` that operators
  actually receive; and
* bytes that are not the approved artifact are refused under *every* name,
  including the exact canonical filename.

Everything that could plausibly be offered in place of the Board of Record —
Board I-H, the superseded predecessor, an unapproved candidate, a pytest
fixture, a synthetic workbook, a truncated or corrupted file, a re-saved copy —
is refused, and refused with a positive identification where one is possible.

The schema and identity layers are exercised directly, because an artifact that
fails the digest gate never reaches them: a fabricated workbook cannot be used
to test row validation, so synthetic grids are fed to the validators instead.
"""

