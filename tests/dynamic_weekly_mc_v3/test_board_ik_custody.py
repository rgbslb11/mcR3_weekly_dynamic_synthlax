def test_the_mounted_artifact_is_the_approved_binary():
    assert APPROVED.exists()
    assert hashlib.sha256(APPROVED.read_bytes()).hexdigest() == (
        bor.BOARD_OF_RECORD_APPROVED_SHA256
    )
    assert APPROVED.stat().st_size == bor.BOARD_OF_RECORD_APPROVED_BYTES


def test_the_content_digest_reproduces_the_registered_hash_spec_v1_value():
    """HASH-SPEC-V1 over 'Board I-K'!A3:Q124, reproduced rather than asserted."""
    assert bor.board_content_sha256(APPROVED) == bor.BOARD_OF_RECORD_CONTENT_SHA256


def test_custody_status_reports_verified_and_emits_no_blocker():
    status = bor.board_of_record_status(APPROVED)
    assert status["custody"] == bor.CUSTODY_VERIFIED
    assert status["verified"] is True
    assert status["blocker"] is None
    assert status["historical_board_substitutable"] is False
    assert bor.board_of_record_blockers(APPROVED) == []


def test_the_board_exposes_121_rows_ranked_one_through_121(board):
    assert board.row_count == bor.BOARD_EXPECTED_ROWS == 121
    assert [r.rank for r in board.rows] == list(range(1, 122))
    assert len(set(board.order_by_master_team_id())) == 121
    assert board.sha256 == bor.BOARD_OF_RECORD_APPROVED_SHA256
    assert board.content_sha256 == bor.BOARD_OF_RECORD_CONTENT_SHA256


def test_the_board_binds_to_the_governed_universe(board, canonical_index):
    """121 FBS_MEMBER, 13 SCHEDULE_ONLY_FCS, 134 schedule identities — unchanged."""
    assert len(canonical_index) == 134
    fbs = {s for s, r in canonical_index.items() if r["entity_scope"] == "FBS_MEMBER"}
    fcs = {
        s for s, r in canonical_index.items()
        if r["entity_scope"] == "SCHEDULE_ONLY_FCS"
    }
    assert len(fbs) == 121 and len(fcs) == 13

    bor.validate_against_canonical_universe(board, canonical_index)
    schedule_ids = board.order_by_schedule_id(canonical_index)
    assert len(schedule_ids) == 121
    assert set(schedule_ids) == fbs
    # No schedule-only FCS entity is ranked, and none can be: FCS entities carry
    # no master_team_id in the canonical index at all.
    assert not (set(schedule_ids) & fcs)
    assert all(
        canonical_index[s]["master_team_id"] is None for s in fcs
    )


def test_the_ordering_is_rank_order_and_maps_through_governed_identifiers(
    board, canonical_index
):
    """Ordering comes from Master Team ID, never from team names."""
    assert board.order_by_schedule_id(canonical_index)[0] == (
        canonical_index[
            next(
                s for s, r in canonical_index.items()
                if r["master_team_id"] == board.rows[0].master_team_id
            )
        ]["schedule_id"]
    )


