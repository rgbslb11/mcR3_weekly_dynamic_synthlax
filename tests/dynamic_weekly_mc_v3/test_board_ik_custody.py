def test_a_synthetic_workbook_with_the_right_shape_is_refused(tmp_path):
    """Correct sheet, correct 17 columns, correct 121 rows — and still not the Board."""
    synthetic = _synthetic_board(tmp_path / "synthetic.xlsx", _plausible_rows())
    grid = bor._read_board_grid(synthetic)
    # It really does satisfy schema and internal identity...
    rows = bor._validate_identity(bor._validate_schema(grid, synthetic), synthetic)
    assert len(rows) == 121
    # ...and is refused anyway, because content identity is what governs.
    assert bor.board_of_record_status(synthetic)["custody"] == (
        bor.CUSTODY_BINARY_MISMATCH
    )
    with pytest.raises(GovernanceBlock):
        bor.require_board_of_record(synthetic)


def test_a_truncated_workbook_is_refused(tmp_path):
    truncated = tmp_path / bor.BOARD_OF_RECORD_FILENAME
    truncated.write_bytes(APPROVED.read_bytes()[: bor.BOARD_OF_RECORD_APPROVED_BYTES // 2])
    assert not zipfile.is_zipfile(truncated)
    assert bor.board_of_record_status(truncated)["custody"] == (
        bor.CUSTODY_BINARY_MISMATCH
    )
    with pytest.raises(GovernanceBlock):
        bor.require_board_of_record(truncated)
    # Read directly, it is classified as an unreadable container, not as rows.
    with pytest.raises(InputValidationError, match=bor.CUSTODY_NOT_A_WORKBOOK):
        bor.board_content_sha256(truncated)


def test_a_corrupted_workbook_is_refused(tmp_path):
    corrupted = tmp_path / bor.BOARD_OF_RECORD_FILENAME
    data = bytearray(APPROVED.read_bytes())
    for i in range(200, 4000, 7):
        data[i] ^= 0xFF
    corrupted.write_bytes(bytes(data))
    assert bor.board_of_record_status(corrupted)["custody"] == (
        bor.CUSTODY_BINARY_MISMATCH
    )
    with pytest.raises(GovernanceBlock):
        bor.require_board_of_record(corrupted)


def test_a_resaved_approved_workbook_is_refused_although_content_survives(tmp_path):
    """The two digests are not interchangeable, and the binary one is not waived.

    A re-save preserves the governed table and loses the container bytes. For
    the schedule, a ruling accepts that trade. For the Board of Record no ruling
    does, so the artifact is refused even though its rows are provably intact.
    """
    resaved = tmp_path / bor.BOARD_OF_RECORD_FILENAME
    shutil.copy(APPROVED, resaved)
    wb = load_workbook(resaved)
    wb.save(resaved)

    assert bor.board_content_sha256(resaved) == bor.BOARD_OF_RECORD_CONTENT_SHA256
    assert hashlib.sha256(resaved.read_bytes()).hexdigest() != (
        bor.BOARD_OF_RECORD_APPROVED_SHA256
    )
    assert bor.board_of_record_status(resaved)["custody"] == bor.CUSTODY_BINARY_MISMATCH
    with pytest.raises(GovernanceBlock):
        bor.require_board_of_record(resaved)


def test_an_edited_approved_workbook_loses_the_content_digest(tmp_path):
    """An edit is distinguishable from a re-save, which is why both are tracked."""
    edited = tmp_path / bor.BOARD_OF_RECORD_FILENAME
    shutil.copy(APPROVED, edited)
    wb = load_workbook(edited)
    wb[bor.BOARD_SHEET]["B4"] = "NOT THE APPROVED TEAM"
    wb.save(edited)
    assert bor.board_content_sha256(edited) != bor.BOARD_OF_RECORD_CONTENT_SHA256


