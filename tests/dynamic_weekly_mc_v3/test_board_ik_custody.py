def _board_from_ids(ids: list[str]) -> bor.BoardOfRecord:
    return bor.BoardOfRecord(
        identity=bor.BOARD_OF_RECORD_FILENAME,
        path=APPROVED,
        sha256=bor.BOARD_OF_RECORD_APPROVED_SHA256,
        content_sha256=bor.BOARD_OF_RECORD_CONTENT_SHA256,
        rows=tuple(
            bor.BoardRow(
                rank=i,
                team_name=f"Team {i}",
                short_name=f"T{i}",
                conference="Test",
                master_team_id=mid,
                committee=0.5,
                power=0.5,
            )
            for i, mid in enumerate(ids, start=1)
        ),
    )


